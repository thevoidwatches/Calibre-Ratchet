// Regenerates www/error.html from error.template.html + www/offline.js +
// www/offline.css, inlining both assets. See the comment in the template for
// why inlining is mandatory. Run before `npx cap copy android`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const read = p => readFileSync(join(here, p), "utf8");

// The one place the server's address is written down. offline.js carries a
// placeholder so it stays runnable under node; the real address lives in
// capacitor.config.json, which is where the app itself reads it, so the two
// cannot drift apart.
const SERVER_LINE = /^export const SERVER = "[^"]*";$/m;
let config;
try {
  config = JSON.parse(read("capacitor.config.json"));
} catch (e) {
  throw new Error("cannot read shell/capacitor.config.json — copy " +
                  "capacitor.config.example.json to it and put your own " +
                  "server address in it (" + e.message + ")");
}
const url = (config.server || {}).url;
if (!url) throw new Error("capacitor.config.json has no server.url");
// Origin only: server.url ends in /ui/, and the offline page builds both
// "<SERVER>/health" and "<SERVER>/ui/" from this.
const origin = new URL(url).origin;

let js = read("www/offline.js");
if (js.includes("</script>"))
  throw new Error("offline.js contains '</script>' — cannot be inlined");
if (!SERVER_LINE.test(js))
  throw new Error("offline.js has no 'export const SERVER = \"...\";' line " +
                  "to substitute — the error page would ship the wrong address");
js = js.replace(SERVER_LINE, () => `export const SERVER = "${origin}";`);

const banner = "<!-- GENERATED by build-error-page.mjs — edit " +
  "error.template.html / offline.js / offline.css instead. -->\n";
// Function replacements so '$' sequences in the assets stay literal.
const out = banner + read("error.template.html")
  .replace("@@CSS@@", () => read("www/offline.css").trim())
  .replace("@@JS@@", () => js.trim());

writeFileSync(join(here, "www/error.html"), out);
console.log(`www/error.html regenerated (server ${origin})`);
